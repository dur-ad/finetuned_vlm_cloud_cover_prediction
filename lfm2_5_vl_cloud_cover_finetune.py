"""## Load & Format Your Dataset"""

import json, random
from PIL import Image
from collections import defaultdict, Counter

def load_jsonl(path):
    with open(path) as f:
        return [json.loads(l) for l in f]

train_records = load_jsonl(f"{DATASET_DIR}/train.jsonl")
val_records   = load_jsonl(f"{DATASET_DIR}/val.jsonl")

# ── Rebalance training set ──
buckets = defaultdict(list)
for r in train_records:
    buckets[r["cloud_bucket"]].append(r)

print("Before:", {k: len(v) for k, v in buckets.items()})

max_count = max(len(v) for v in buckets.values())
balanced = []
for bucket, samples in buckets.items():
    oversampled = (samples * ((max_count // len(samples)) + 1))[:max_count]
    balanced.extend(oversampled)

random.seed(42)
random.shuffle(balanced)

print("After :", dict(Counter(r["cloud_bucket"] for r in balanced)))
print(f"Total  : {len(balanced)} training samples")

# ── Convert to conversation format ──
SYSTEM_PROMPT = "You are a satellite imagery analyst. Analyze Sentinel-2 images and provide accurate cloud cover assessments."

def convert_to_conversation(record):
    img_path = f"{DATASET_DIR}/images/{record['image']}"
    image = Image.open(img_path).convert("RGB")
    return {"messages": [
        {"role": "user", "content": [
            {"type": "text",  "text": record["instruction"]},
            {"type": "image", "image": image},
        ]},
        {"role": "assistant", "content": [
            {"type": "text", "text": record["response"]}
        ]},
    ]}

print("\nConverting training set...")
train_dataset = [convert_to_conversation(r) for r in balanced]
print("Converting validation set...")
val_dataset   = [convert_to_conversation(r) for r in val_records]
print(f" Ready: {len(train_dataset)} train / {len(val_dataset)} val")

