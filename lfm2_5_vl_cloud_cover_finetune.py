"""## Fine-tune the Model"""

from unsloth.trainer import UnslothVisionDataCollator
from trl import SFTTrainer, SFTConfig

FastVisionModel.for_training(model)  # Switch back to training mode

# Save checkpoints directly to Drive so you don't lose progress
OUTPUT_DIR = "/content/drive/MyDrive/lfm2_clean_cloud_checkpoints_balanced"

trainer = SFTTrainer(
    model         = model,
    tokenizer     = tokenizer,
    data_collator = UnslothVisionDataCollator(model, tokenizer),  # Required for vision!
    train_dataset = train_dataset,
    args = SFTConfig(
        output_dir                  = OUTPUT_DIR,
        per_device_train_batch_size = 2,
        gradient_accumulation_steps = 4,      # effective batch = 8
        num_train_epochs            = 5,       # full training (change to max_steps=30 for quick test)
        # max_steps                 = 30,     # ← uncomment for a quick 1-minute test run
        warmup_steps                = 20,
        learning_rate               = 1e-4,
        logging_steps               = 5,
        optim                       = "adamw_8bit",
        weight_decay                = 0.001,
        lr_scheduler_type           = "cosine",
        seed                        = 3407,
        report_to                   = "none",
        # ── Required for vision fine-tuning (from Liquid AI notebook) ──
        remove_unused_columns       = False,
        dataset_text_field          = "",
        dataset_kwargs              = {"skip_prepare_dataset": True},
        max_length                  = 2048,
        save_steps                  = 50,      # checkpoint every 50 steps → Drive
    ),
)

# Show GPU memory before training
gpu_stats = torch.cuda.get_device_properties(0)
start_mem = round(torch.cuda.max_memory_reserved() / 1024**3, 3)
max_mem   = round(gpu_stats.total_memory / 1024**3, 3)
print(f"GPU: {gpu_stats.name} | Max memory: {max_mem} GB | Reserved: {start_mem} GB")

print("\n Starting fine-tuning...")
trainer_stats = trainer.train()

# Memory stats after
used_mem = round(torch.cuda.max_memory_reserved() / 1024**3, 3)
print(f"\n Training complete!")
print(f"   Time       : {round(trainer_stats.metrics['train_runtime']/60, 2)} minutes")
print(f"   Peak VRAM  : {used_mem} GB / {max_mem} GB ({round(used_mem/max_mem*100, 1)}%)")

